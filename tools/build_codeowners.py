"""Generate .github/CODEOWNERS (Kyle, 2026-10-14: access-level approval).

Who may approve a change, by path:

  everything                         the site admins (ADMIN_OWNERS)
  a project's page and facts file    the admins and that project's `owners`
    /content/projects/<id>.md          (data/projects.json)
    /data/projects/<id>.json
  .github/, data/projects.json,      the admins only, written last so nothing
  tools/, api/, js/, cms/,           widens them: CODEOWNERS owns itself, and a
  vercel.json                        project owner can never change who owns what

GitHub enforces it once the ruleset on main is on (a pull request then needs
one approval from a code owner of every file it changes; not on yet: see
docs/cms-plan.md, item 0). The editor shows Approve by the same rule
(js/cms-core.js ownsAll). tools/check.py fails when the file
is not exactly this script's output, so the two never drift:

    python3 tools/build_codeowners.py          # rewrite .github/CODEOWNERS
    python3 tools/build_codeowners.py --check  # exit 1 when it differs

ADMIN_OWNERS is the people who approve the admin-owned paths (the repository's
Admins and Maintainers): a code change by Desert Mango. A name without Write
access is ignored by GitHub until it has it.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ".github/CODEOWNERS"
INDEX = "data/projects.json"
# The people who approve admin-owned paths: the repository's Admins and Maintainers (the editor shows them
# Approve everywhere), so every new Admin or Maintainer is added here too. NBauschmann (Nathalie, the lab's
# Admin to be) is listed ahead: GitHub ignores a name without Write access until she is added, and from then
# her approval counts with no further change.
ADMIN_OWNERS = ("desert-mango-robotics", "NBauschmann")
ADMIN_ONLY = ("/.github/", "/data/projects.json", "/tools/", "/api/", "/js/", "/cms/", "/vercel.json")

HEADER = """\
# GENERATED by tools/build_codeowners.py from data/projects.json: do not edit by hand.
# Run `python3 tools/build_codeowners.py` after changing a project's owners; tools/check.py fails while
# this file differs from that script's output.
#
# Who may approve a change (Kyle, 2026-10-14). The site editor shows Approve by this rule, and GitHub
# requests these reviewers on every pull request. GitHub ENFORCES it once the ruleset on main is on (one
# approval from a code owner of every changed file): not yet, see docs/cms-plan.md (item 0). Later lines win.
"""


def render(index):
    """The CODEOWNERS text for a parsed data/projects.json index."""
    admins = " ".join(f"@{a}" for a in ADMIN_OWNERS)
    rows = [("*", admins)]
    projects = index.get("projects") if isinstance(index, dict) else None
    for p in projects if isinstance(projects, list) else []:
        if not isinstance(p, dict) or not isinstance(p.get("id"), str):
            continue
        owners = [o for o in p.get("owners", []) if isinstance(o, str)] if isinstance(p.get("owners"), list) else []
        extra = [o for o in owners if o.lower() not in {a.lower() for a in ADMIN_OWNERS}]
        if not extra:
            continue                                   # admins only: the "*" line says it
        who = " ".join([admins] + [f"@{o}" for o in extra])
        rows.append((f"/content/projects/{p['id']}.md", who))
        rows.append((f"/data/projects/{p['id']}.json", who))
    rows.extend((path, admins) for path in ADMIN_ONLY)
    width = max(len(path) for path, _ in rows) + 2
    return HEADER + "\n" + "".join(f"{path.ljust(width)}{who}\n" for path, who in rows)


def expected(root=ROOT):
    return render(json.loads((Path(root) / INDEX).read_text(encoding="utf-8")))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when .github/CODEOWNERS differs; write nothing")
    args = ap.parse_args(argv)
    want = expected()
    path = ROOT / OUT
    have = path.read_text(encoding="utf-8") if path.exists() else None
    if args.check:
        if have != want:
            print(f"{OUT} differs from tools/build_codeowners.py's output: run python3 tools/build_codeowners.py")
            return 1
        print(f"{OUT}: in sync")
        return 0
    path.write_text(want, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
