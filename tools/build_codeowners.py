"""Generate .github/CODEOWNERS from data/graph/edit-access.json.

Who may approve a change, by path:

  everything                         the site admins (ADMIN_OWNERS)
  a project's page and facts file    the admins and that project's editors
    /content/projects/<id>.md          (data/graph/edit-access.json)
    /data/projects/<id>.json
  .github/, data/projects.json,      the admins only, written last so nothing
  tools/, api/, js/, cms/,           widens them: CODEOWNERS owns itself, and a
  vercel.json                        project editor can never change who edits what

A project's editors (Kyle, 2026-10-19) come from tools/build_edit_access.py,
the one place the rule lives: commits first (one commit in the project's own
lab repos), and an admin's `add` or `remove` in data/projects.json always wins.
The contributor counts are rebuilt daily (.github/workflows/derive.yml).

GitHub ENFORCES this file: the ruleset `main-review` on main is on since
2026-10-15 (a pull request needs one approval from a code owner of every file
it changes). The editor shows Approve by the same edit-access.json. A name
without Write access to this repository is ignored by GitHub until it has it.

tools/derive.py runs this after build_edit_access.py on every call, and
tools/check.py fails when the file is not exactly this script's output, so the
two never drift:

    python3 tools/build_codeowners.py          # rewrite .github/CODEOWNERS
    python3 tools/build_codeowners.py --check  # exit 1 when it differs

Without data/graph/edit-access.json it writes nothing and exits 1 (it would
otherwise drop every project editor). ADMIN_OWNERS is the people who approve
the admin-owned paths (the repository's Admins and Maintainers): a code change
by Desert Mango.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ".github/CODEOWNERS"
ACCESS = "data/graph/edit-access.json"
# The people who approve admin-owned paths: the repository's Admins and Maintainers (the editor shows them
# Approve everywhere), so every new Admin or Maintainer is added here too. NBauschmann (Nathalie, the lab's
# Admin to be) is listed ahead: GitHub ignores a name without Write access until she is added, and from then
# her approval counts with no further change.
ADMIN_OWNERS = ("desert-mango-robotics", "NBauschmann")
ADMIN_ONLY = ("/.github/", "/data/projects.json", "/tools/", "/api/", "/js/", "/cms/", "/vercel.json")

HEADER = """\
# GENERATED by tools/build_codeowners.py from data/graph/edit-access.json: do not edit by hand.
# tools/derive.py rewrites it after every change of who may edit; tools/check.py fails while this file
# differs from that script's output.
#
# Who may approve a change. GitHub ENFORCES it: the ruleset main-review on main is ON since 2026-10-15 (one
# approval from a code owner of every changed file). A project's editors: commits first (one commit in the
# project's own lab repos), and an admin's add or remove in data/projects.json always wins; the commit
# counts are rebuilt daily. A name without Write access is ignored by GitHub. Later lines win.
"""


def render(access):
    """The CODEOWNERS text for a parsed data/graph/edit-access.json (never raises on a bad shape)."""
    admins = " ".join(f"@{a}" for a in ADMIN_OWNERS)
    admin_keys = {a.lower() for a in ADMIN_OWNERS}
    rows = [("*", admins)]
    projects = access.get("projects") if isinstance(access, dict) else None
    for pid in sorted(projects) if isinstance(projects, dict) else []:
        entry = projects[pid]
        editors = entry.get("editors") if isinstance(entry, dict) else None
        logins = [e["login"] for e in editors if isinstance(e, dict) and isinstance(e.get("login"), str)] \
            if isinstance(editors, list) else []
        extra = [o for o in logins if o.lower() not in admin_keys]
        if not extra:
            continue                                   # admins only: the "*" line says it
        who = " ".join([admins] + [f"@{o}" for o in extra])
        rows.append((f"/content/projects/{pid}.md", who))
        rows.append((f"/data/projects/{pid}.json", who))
    rows.extend((path, admins) for path in ADMIN_ONLY)
    width = max(len(path) for path, _ in rows) + 2
    return HEADER + "\n" + "".join(f"{path.ljust(width)}{who}\n" for path, who in rows)


def expected(root=ROOT):
    """The CODEOWNERS text for root's edit-access.json (FileNotFoundError / ValueError when it is missing or bad)."""
    return render(json.loads((Path(root) / ACCESS).read_text(encoding="utf-8")))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(ROOT), help="the repository to read and write (default: this one)")
    ap.add_argument("--check", action="store_true", help="exit 1 when .github/CODEOWNERS differs; write nothing")
    args = ap.parse_args(argv)
    try:
        want = expected(args.root)
    except FileNotFoundError:
        print(f"build_codeowners: FAILED — {ACCESS} is missing: run python3 tools/build_edit_access.py first; "
              f"nothing written")
        return 1
    except ValueError as exc:
        print(f"build_codeowners: FAILED — {ACCESS} is unreadable ({exc}); nothing written")
        return 1
    path = Path(args.root) / OUT
    have = path.read_text(encoding="utf-8") if path.exists() else None
    if args.check:
        if have != want:
            print(f"{OUT} differs from tools/build_codeowners.py's output: run python3 tools/build_codeowners.py")
            return 1
        print(f"{OUT}: in sync")
        return 0
    if have != want:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
